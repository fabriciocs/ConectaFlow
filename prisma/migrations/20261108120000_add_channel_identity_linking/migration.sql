-- Additive identity-linking persistence. This migration is intentionally not applied here.
CREATE TABLE `ChannelIdentityLink` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `sessionId` VARCHAR(191) NOT NULL,
  `channel` VARCHAR(32) NOT NULL DEFAULT 'WHATSAPP',
  `channelAccountId` VARCHAR(191) NOT NULL,
  `subjectHash` CHAR(64) NOT NULL,
  `status` ENUM('ACTIVE', 'REVOKED', 'EXPIRED', 'SUSPENDED') NOT NULL DEFAULT 'ACTIVE',
  `linkedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `expiresAt` DATETIME(3) NULL,
  `revokedAt` DATETIME(3) NULL,
  `authTime` DATETIME(3) NULL,
  `authMethod` VARCHAR(64) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  UNIQUE INDEX `channel_identity_scope_uq` (`tenantId`, `channel`, `channelAccountId`, `subjectHash`),
  INDEX `channel_identity_user_status_idx` (`tenantId`, `userId`, `status`),
  INDEX `channel_identity_expiry_idx` (`tenantId`, `status`, `expiresAt`),
  INDEX `channel_identity_subject_idx` (`sessionId`, `subjectHash`, `status`),
  PRIMARY KEY (`id`),
  CONSTRAINT `ChannelIdentityLink_tenantId_fkey` FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `ChannelIdentityLink_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `ChannelIdentityLink_sessionId_fkey` FOREIGN KEY (`sessionId`) REFERENCES `Session` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `ChannelLinkChallenge` (
  `id` VARCHAR(191) NOT NULL,
  `tenantId` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NULL,
  `sessionId` VARCHAR(191) NOT NULL,
  `channel` VARCHAR(32) NOT NULL DEFAULT 'WHATSAPP',
  `channelAccountId` VARCHAR(191) NOT NULL,
  `subjectHash` CHAR(64) NOT NULL,
  `tokenHash` CHAR(64) NOT NULL,
  `purpose` ENUM('LINK_IDENTITY') NOT NULL DEFAULT 'LINK_IDENTITY',
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `expiresAt` DATETIME(3) NOT NULL,
  `consumedAt` DATETIME(3) NULL,
  `revokedAt` DATETIME(3) NULL,
  `attemptCount` INTEGER NOT NULL DEFAULT 0,
  `requestId` VARCHAR(191) NULL,
  UNIQUE INDEX `channel_link_token_hash_uq` (`tokenHash`),
  UNIQUE INDEX `channel_link_request_uq` (`tenantId`, `sessionId`, `requestId`),
  INDEX `channel_link_subject_idx` (`tenantId`, `sessionId`, `subjectHash`, `purpose`, `expiresAt`),
  INDEX `channel_link_expiry_idx` (`tenantId`, `expiresAt`, `revokedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `ChannelLinkChallenge_tenantId_fkey` FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `ChannelLinkChallenge_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `ChannelLinkChallenge_sessionId_fkey` FOREIGN KEY (`sessionId`) REFERENCES `Session` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
