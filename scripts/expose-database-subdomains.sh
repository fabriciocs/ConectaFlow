#!/usr/bin/env bash
set -euo pipefail

# Safe database-subdomain provisioner.
#
# This script intentionally does not expose MySQL/PostgreSQL directly by default.
# It audits the host and can generate an Nginx stream configuration only when the
# operator explicitly opts in, supplies an IP allowlist, and provides a mapping.
# Prefer a VPN/private network or a managed database gateway for production.

APP_DIR="${APP_DIR:-/opt/WA-AKG}"
CONFIG_FILE="${CONFIG_FILE:-$APP_DIR/deploy/database-subdomains.conf}"
NGINX_STREAM_DIR="${NGINX_STREAM_DIR:-/etc/nginx/stream-conf.d}"
NGINX_STREAM_FILE="$NGINX_STREAM_DIR/evomenu-databases.conf"

usage() {
  cat <<'EOF'
Uso:
  expose-database-subdomains.sh audit
  expose-database-subdomains.sh plan
  expose-database-subdomains.sh apply --confirm-risk

Variáveis obrigatórias para `apply`:
  DB_ALLOWLIST_CIDRS="203.0.113.10/32,198.51.100.0/24"
  DB_BACKENDS="crm=13306@127.0.0.1:3307,analytics=13307@10.0.0.12:3306"

O script não cria DNS nem certificados. Antes de aplicar:
  1. Crie os registros crm.evomenu.com.br e analytics.evomenu.com.br.
  2. Garanta TLS/mTLS no gateway ou use uma VPN.
  3. Confirme que o Nginx possui o módulo `stream`.

Importante: clientes MySQL comuns não enviam SNI de forma confiável. Para mais
de um banco, prefira portas distintas, VPN ou um gateway de banco autenticado.
EOF
}

die() { echo "ERRO: $*" >&2; exit 1; }

require_root() { [ "$(id -u)" -eq 0 ] || die "execute como root somente para apply"; }

parse_csv() {
  local value="$1" item
  IFS=',' read -ra items <<< "$value"
  for item in "${items[@]}"; do
    item="${item//[[:space:]]/}"
    [ -n "$item" ] || die "lista contém item vazio"
    printf '%s\n' "$item"
  done
}

audit() {
  echo "== WA-AKG database exposure audit =="
  echo "host=$(hostname -f 2>/dev/null || hostname)"
  echo "date=$(date -Is)"
  echo
  echo "[listeners]"
  if command -v ss >/dev/null 2>&1; then
    ss -ltnp | awk 'NR == 1 || /:3306|:3307|:5432|:43000|:80|:443/' || true
  else
    echo "ss não instalado"
  fi
  echo
  echo "[compose risks]"
  if [ -f "$APP_DIR/docker-compose.yml" ]; then
    grep -nE '^[[:space:]]*-[[:space:]]*"?[0-9]+:3306|^[[:space:]]*-[[:space:]]*"?[0-9]+:43000' \
      "$APP_DIR/docker-compose.yml" || echo "nenhuma publicação conhecida encontrada"
  fi
  echo
  echo "[configuration]"
  echo "config=$CONFIG_FILE"
  [ -f "$CONFIG_FILE" ] && sed -n '1,160p' "$CONFIG_FILE" || echo "configuração ainda não criada"
  echo
  echo "RESULTADO: banco deve permanecer privado; publicar porta TCP sem VPN/mTLS é rejeitado."
}

render() {
  [ -n "${DB_ALLOWLIST_CIDRS:-}" ] || die "DB_ALLOWLIST_CIDRS não definido"
  [ -n "${DB_BACKENDS:-}" ] || die "DB_BACKENDS não definido"

  local cidr backend name target host port
  local allow=""
  while read -r cidr; do allow+="        allow $cidr;\n"; done < <(parse_csv "$DB_ALLOWLIST_CIDRS")

  printf '%s\n' '# Generated by scripts/expose-database-subdomains.sh; do not edit.'
  printf '%s\n' '# Requires nginx stream module and DNS records pointing to this host.'
  IFS=',' read -ra backends <<< "$DB_BACKENDS"
  for backend in "${backends[@]}"; do
    name="${backend%%=*}"; target="${backend#*=}"
    [[ "$name" =~ ^[a-z0-9-]+$ ]] || die "subdomínio inválido: $name"
    [[ "$target" == *@*:* ]] || die "backend inválido para $name; use nome=porta-exposta@host:porta"
    local listen="${target%%@*}"
    target="${target#*@}"
    [[ "$listen" =~ ^[0-9]+$ ]] || die "porta exposta inválida para $name"
    host="${target%:*}"; port="${target##*:}"
    [[ "$port" =~ ^[0-9]+$ ]] || die "porta inválida para $name"
    cat <<EOF
upstream db_${name} { server ${host}:${port}; }
server {
    listen 0.0.0.0:${listen};
    proxy_pass db_${name};
    proxy_connect_timeout 5s;
    proxy_timeout 300s;
$(printf '%b' "$allow")}
EOF
  done
}

plan() {
  echo "== plano (nenhuma alteração será feita) =="
  audit
  echo
  echo "[configuração que seria gerada]"
  render
}

apply() {
  require_root
  [ "${1:-}" = "--confirm-risk" ] || die "apply exige --confirm-risk"
  command -v nginx >/dev/null || die "nginx não encontrado"
  nginx -V 2>&1 | grep -q -- '--with-stream' || die "Nginx sem módulo stream"
  [ -n "${DB_ALLOWLIST_CIDRS:-}" ] || die "DB_ALLOWLIST_CIDRS não definido"
  [ -n "${DB_BACKENDS:-}" ] || die "DB_BACKENDS não definido"

  install -d -m 0750 "$NGINX_STREAM_DIR"
  local tmp
  tmp="$(mktemp)"
  render > "$tmp"
  install -o root -g root -m 0640 "$tmp" "$NGINX_STREAM_FILE"
  rm -f "$tmp"
  nginx -t
  echo "Configuração instalada em $NGINX_STREAM_FILE."
  echo "Nenhum reload foi executado: valide o DNS, TLS/mTLS e firewall antes de recarregar."
  echo "Para aplicar após revisão: systemctl reload nginx"
}

case "${1:-}" in
  audit) audit ;;
  plan) plan ;;
  apply) shift; apply "$@" ;;
  *) usage; exit 2 ;;
esac
